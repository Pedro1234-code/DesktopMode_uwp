[CmdletBinding()]
param(
    [string] $ReactOSRoot = (Join-Path $PSScriptRoot '../reactos-master'),
    [string] $OutputPath = (Join-Path $PSScriptRoot '../Bridge/GeneratedExportAliases.inl'),
    [switch] $Check
)

$ErrorActionPreference = 'Stop'

function Read-SpecExports([string[]] $Lines) {
    foreach ($line in $Lines) {
        # A forwarder can contain #ordinal, so only strip comments after whitespace.
        $text = ($line -replace '\s+#.*$', '').Trim()
        if ($text -notmatch '^(?<ordinal>@|\d+)\s+(?<kind>stdcall|cdecl|varargs|extern)\s+(?<options>(?:-\S+\s+)*)(?<name>[^\s(]+)(?:\([^)]*\))?(?:\s+(?<target>\S+))?\s*$') {
            continue
        }
        $fields = $Matches.Clone()
        $options = $fields.options
        if ($options -match '(?:^|\s)-stub(?:\s|$)') { continue }
        if ($options -match '(?:^|\s)-arch=([^\s]+)') {
            $architectures = $Matches[1].Split(',')
            if ('x86_64' -notin $architectures -and 'win64' -notin $architectures) { continue }
        }
        if ($options -match '(?:^|\s)-version=([^\s]+)') {
            $range = $Matches[1]
            if ($range -match '^(0x[0-9a-f]+)(?:(\+)|-(0x[0-9a-f]+))?$') {
                $minimum = [Convert]::ToInt32($Matches[1].Substring(2),16)
                $maximum = if ($Matches[2]) { [int]::MaxValue } elseif ($Matches[3]) {
                    [Convert]::ToInt32($Matches[3].Substring(2),16)
                } else { $minimum }
                if (0xA00 -lt $minimum -or 0xA00 -gt $maximum) { continue }
            } else { throw "Unsupported version selector: $range" }
        }
        [pscustomobject]@{
            Name = $fields.name
            Ordinal = if ($fields.ordinal -eq '@') { 0 } else { [int]$fields.ordinal }
            Named = $options -notmatch '(?:^|\s)-noname(?:\s|$)'
            Target = $fields.target
        }
    }
}

# Regression fixtures cover explicit ordinals, forwarders, architecture/version
# filtering and exports whose ordinal is assigned by the source build system.
$fixtures = @(Read-SpecExports @(
    '17 stdcall InitCommonControls()',
    '@ stdcall Forward(ptr) kernel32.Target',
    '4 stdcall -noname Hidden(ptr)',
    '5 stub Missing',
    '11 stdcall -stub MissingFlag()',
    '6 stdcall -arch=i386 Only32()',
    '7 stdcall -arch=x86_64 Only64()',
    '8 stdcall -version=0x501-0x502 Old()',
    '9 stdcall -version=0x600+ Current()',
    '10 stdcall OrdinalForward() other.#12 # comment'
))
if ($fixtures.Count -ne 6 -or $fixtures[1].Ordinal -ne 0 -or
    $fixtures[1].Target -cne 'kernel32.Target' -or $fixtures[2].Named -or
    $fixtures[-1].Target -cne 'other.#12') {
    throw ('Export parser regression fixtures failed: ' + ($fixtures | ConvertTo-Json -Compress))
}

$specs = @{}
foreach ($module in @('advapi32','bcrypt','combase','comctl32','comdlg32','crypt32',
    'kernel32','kernelbase','msimg32','msvcrt','ole32','oleaut32','shell32','shcore','shlwapi','uxtheme','version')) {
    $specs[$module] = "dll/win32/$module/$module.spec"
}
$specs['user32'] = 'subsystems/win/win32k/user/user32/user32.spec'
$specs['gdi32'] = 'subsystems/win/win32k/gdi/gdi32/gdi32.spec'
$specs['ntdll'] = 'dll/ntdll/def/ntdll.spec'

$rows = [Collections.Generic.List[string]]::new()
$rows.Add('// Generated by Tools/Generate-ExportAliases.ps1. Do not edit by hand.')
$rows.Add('// Source: ReactOS .spec export metadata, targeting Windows 10 x64.')
$rows.Add('// Only explicit ordinals and declared aliases are included. Stubs are excluded.')
$total = 0
foreach ($module in ($specs.Keys | Sort-Object)) {
    $relative = $specs[$module]
    $path = Join-Path $ReactOSRoot $relative
    if (-not (Test-Path -LiteralPath $path)) { throw "Missing export specification: $relative" }
    $exports = @(Read-SpecExports (Get-Content -LiteralPath $path))
    $named = [Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
    foreach ($export in $exports) { if ($export.Named) { [void]$named.Add($export.Name) } }
    $keys = [Collections.Generic.HashSet[string]]::new([StringComparer]::Ordinal)
    $rows.Add("// $relative")
    foreach ($export in $exports) {
        $targetLibrary = "$module.dll"
        $targetName = $export.Name
        $targetOrdinal = 0
        if ($export.Target -match '^(?<dll>[A-Za-z0-9_-]+)(?:\.dll)?\.(?<symbol>[^.]+)$') {
            $targetLibrary = $Matches.dll.ToLowerInvariant() + '.dll'
            $targetName = $Matches.symbol
            if ($targetName -match '^#(\d+)$') {
                $targetOrdinal = [int]$Matches[1]
                $targetName = ''
                if ($targetOrdinal -lt 1 -or $targetOrdinal -gt 65535) { throw 'Invalid target ordinal.' }
            }
        } elseif ($export.Target -and $named.Contains($export.Target)) {
            $targetName = $export.Target
        }
        $forwarded = $targetLibrary -cne "$module.dll" -or $targetName -cne $export.Name
        $sourceNames = @()
        if ($export.Ordinal -gt 0) {
            if ($export.Ordinal -gt 65535) { throw 'Invalid source ordinal.' }
            $sourceNames += [pscustomobject]@{ Name=''; Ordinal=$export.Ordinal }
        }
        if ($export.Named -and $forwarded) {
            $sourceNames += [pscustomobject]@{ Name=$export.Name; Ordinal=0 }
        }
        foreach ($source in $sourceNames) {
            $key = if ($source.Ordinal) { "#$($source.Ordinal)" } else { "name:$($source.Name)" }
            if (-not $keys.Add($key)) { throw "Ambiguous export $module!$key" }
            foreach ($value in @($source.Name,$targetName)) {
                if ($value.Contains('"') -or $value.Contains('\')) { throw 'Invalid export identifier.' }
            }
            $rows.Add(('{{ L"{0}.dll", L"{1}", {2}, L"{3}", L"{4}", {5} }},' -f
                $module,$source.Name,$source.Ordinal,$targetLibrary,$targetName,$targetOrdinal))
            ++$total
        }
    }
}
$content = ($rows -join "`n") + "`n"
if ($Check) {
    if (-not (Test-Path -LiteralPath $OutputPath) -or
        [IO.File]::ReadAllText($OutputPath).Replace("`r`n","`n") -cne $content) {
        throw 'Generated export aliases are out of date.'
    }
} else {
    [IO.File]::WriteAllText($OutputPath,$content,[Text.UTF8Encoding]::new($false))
}
Write-Output "Export parser fixtures passed; $total aliases across $($specs.Count) module specifications."